# ============================================================
# FLATTEN SUB-KRITERIA
# ============================================================

def semua_sub_kriteria_flat():

    hasil = []
    for kategori_kode, kategori in RUBRIC.items():
        kategori_nama = kategori["name"]
        for sub_kode, sub in kategori["subcategories"].items():
            hasil.append({

                "kode": sub_kode,
                "nama": sub["description"],
                "kategori_kode": kategori_kode,
                "kategori_nama": kategori_nama,
                "weight": sub["weight"],
                "elements": sub.get(
                    "elements",
                    []
                )
            })

    return hasil